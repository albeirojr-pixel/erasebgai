let currentLang = "en";
let selectedFile = null;
let resultBlobUrl = null;

const uploadZone      = document.getElementById("uploadZone");
const fileInput       = document.getElementById("fileInput");
const processBtn      = document.getElementById("processBtn");
const uploadSection   = document.getElementById("uploadSection");
const processingState = document.getElementById("processingState");
const resultSection   = document.getElementById("resultSection");
const originalImg     = document.getElementById("originalImg");
const resultImg       = document.getElementById("resultImg");
const downloadBtn     = document.getElementById("downloadBtn");
const newBtn          = document.getElementById("newBtn");

function applyLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (i18n[lang][key] !== undefined) {
      el.innerHTML = i18n[lang][key];
    }
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
}

document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

const browserLang = navigator.language?.slice(0, 2);
if (["es", "pt"].includes(browserLang)) applyLang(browserLang);

uploadZone.addEventListener("click", () => fileInput.click());

uploadZone.addEventListener("dragover", (e) => {
  e.preventDefault();
  uploadZone.classList.add("drag-over");
});

uploadZone.addEventListener("dragleave", () => {
  uploadZone.classList.remove("drag-over");
});

uploadZone.addEventListener("drop", (e) => {
  e.preventDefault();
  uploadZone.classList.remove("drag-over");
  const file = e.dataTransfer.files[0];
  if (file) handleFile(file);
});

fileInput.addEventListener("change", () => {
  if (fileInput.files[0]) handleFile(fileInput.files[0]);
});

function handleFile(file) {
  if (!file.type.startsWith("image/")) {
    alert("Please select a valid image file (JPG, PNG, WEBP).");
    return;
  }
  if (file.size > 10 * 1024 * 1024) {
    alert("File too large. Maximum size is 10MB.");
    return;
  }

  selectedFile = file;

  const reader = new FileReader();
  reader.onload = (e) => {
    let thumb = uploadZone.querySelector(".preview-thumb");
    if (!thumb) {
      thumb = document.createElement("img");
      thumb.className = "preview-thumb";
      thumb.alt = "Preview";
      uploadZone.appendChild(thumb);
    }
    thumb.src = e.target.result;
    uploadZone.classList.add("has-file");
  };
  reader.readAsDataURL(file);

  processBtn.disabled = false;
}

processBtn.addEventListener("click", async () => {
  if (!selectedFile) return;

  uploadSection.style.display   = "none";
  processingState.style.display = "block";
  resultSection.style.display   = "none";

  try {
    const response = await fetch("/api/process", {
      method: "POST",
      headers: { "Content-Type": selectedFile.type },
      body: selectedFile,
    });

    if (!response.ok) {
      let msg = "Error processing image. Please try again.";
      try {
        const data = await response.json();
        if (data.error === "model_loading") {
          msg = "The AI model is warming up. Please wait 20 seconds and try again.";
        } else if (data.error === "rate_limit") {
          msg = "Too many requests. Please wait a moment and try again.";
        }
      } catch (_) {}
      throw new Error(msg);
    }

    const blob = await response.blob();
    if (resultBlobUrl) URL.revokeObjectURL(resultBlobUrl);
    resultBlobUrl = URL.createObjectURL(blob);

    originalImg.src = URL.createObjectURL(selectedFile);
    resultImg.src   = resultBlobUrl;

    const baseName = selectedFile.name.replace(/\.[^.]+$/, "");
    downloadBtn.dataset.filename = `${baseName}-no-bg.png`;

    processingState.style.display = "none";
    resultSection.style.display   = "block";

  } catch (err) {
    processingState.style.display = "none";
    uploadSection.style.display   = "flex";
    alert(err.message);
  }
});

downloadBtn.addEventListener("click", () => {
  if (!resultBlobUrl) return;
  const a = document.createElement("a");
  a.href     = resultBlobUrl;
  a.download = downloadBtn.dataset.filename || "no-background.png";
  a.click();
});

newBtn.addEventListener("click", resetApp);

function resetApp() {
  selectedFile = null;
  fileInput.value = "";
  uploadZone.classList.remove("has-file");
  const thumb = uploadZone.querySelector(".preview-thumb");
  if (thumb) thumb.remove();
  processBtn.disabled = true;
  resultSection.style.display   = "none";
  processingState.style.display = "none";
  uploadSection.style.display   = "flex";
}